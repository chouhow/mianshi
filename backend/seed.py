def _scoring_for(stem: str) -> str:
    for prefix, points in SCORING_POINTS.items():
        if stem.startswith(prefix):
            return points
    return ""


def main():
    backfill = "--backfill" in sys.argv
    questions = load_questions()

    if backfill:
        updated = 0
        for q in questions:
            if not (q.get("scoring_points") or "").strip():
                points = _scoring_for(q["stem"])
                if points:
                    q["scoring_points"] = points
                    q["updated_at"] = now_iso()
                    updated += 1
        save_questions(questions)
        print(f"回填评分标准 {updated} 道（共 {len(questions)} 道）")
        return

    if questions:
        print(f"题库已有 {len(questions)} 道题，跳过播种（可用 --backfill 回填采分点）")
        return
    now = now_iso()
    for stem, answer, explanation, category, difficulty, section in QUESTIONS:
        questions.append({
            "id": new_id("q"),
            "stem": stem,
            "reference_answer": answer,
            "scoring_points": _scoring_for(stem),
            "explanation": explanation,
            "category": category,
            "difficulty": difficulty,
            "section": section,
            "created_at": now,
            "updated_at": now,
        })
    save_questions(questions)
    print(f"已写入 {len(questions)} 道示例题目（含评分标准）")


if __name__ == "__main__":
    main()
